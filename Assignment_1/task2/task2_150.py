#Functions for training and evaluation: CLASSIFICATION

#Train the model
def train_classification(model, train_dataloader, optimizer, criterion, epochs, bin_size):

    """Train a classification model for a given number of epochs."""

    for epoch in range(epochs):
        model.train()
        running_loss = 0.0

        for inputs, hours, minutes in train_dataloader:

            #data agumentation
            #inputs = train_transform(inputs)

            #To use external GPU
            inputs = inputs.to(device)
            hours = hours.to(device)
            minutes = minutes.to(device)

            #total minutes since 00:00 (e.g., 01:30 --> 90 minutes) (before we computed it in the loading chunk)
            total_minutes = hours * 60 + minutes

            #convert the labels from labels in minutes to labels in classes (e.g., class 3)
            labels_class = (total_minutes // bin_size).long()

            #zero the parameter gradients
            optimizer.zero_grad()

            #forward + backward + optimize
            outputs = model(inputs) #predictions
            loss = criterion(outputs, labels_class) #compute loss
            loss.backward() #compute gradients
            optimizer.step() #optimize weights

            #compute running loss
            running_loss += loss.item()

        print(
            f"Epoch {epoch + 1}/{epochs}: "
            f"- Loss = {running_loss/len(train_dataloader):.4f}"
        )

#Validate the model
def evaluate_classification(model, dataloader, bin_size):

    """Evaluate a classification model using the average circular time error."""

    model.eval()
    total_error = 0
    total = 0

    with torch.no_grad():
        for inputs, hours, minutes in dataloader:

            #To use external GPU
            inputs = inputs.to(device)
            hours = hours.to(device)
            minutes = minutes.to(device)
            true_minutes = hours * 60 + minutes

            #Get predictions and classes
            outputs = model(inputs) #predictions (in classes!!!)
            predictions = outputs.argmax(dim=1) #assign to the class with the highest score

            #Convert predicted classes back into total minutes
            predicted_minutes = predictions * bin_size + (bin_size - 1) / 2 #midpoint to represent the class

            #Calculate absolute difference and the circular difference
            difference = torch.abs(predicted_minutes - true_minutes)
            circular_difference = torch.minimum(difference, 720 - difference)

            #Compute the errors
            total_error += circular_difference.sum().item()
            total += minutes.size(0)

    common_sense_error = total_error / total
    return common_sense_error


