#We use the same final CNN (4 conv blocks) for all three approaches,
#only the output layer changes

class Net_4conv(nn.Module):   #Final CNN
    def __init__(self, num_outputs):
        super().__init__()
        #Input image (1, 150, 150) (greyscale)
        self.conv1 = nn.Conv2d(1, 6, 3, padding=1)
        self.pool = nn.MaxPool2d(2, 2)
        self.conv2 = nn.Conv2d(6, 16, 3, padding=1)
        self.conv3 = nn.Conv2d(16, 32, 3, padding=1)
        self.conv4 = nn.Conv2d(32, 64, 3, padding=1)
        self.fc1 = nn.Linear(64 * 9 * 9, 120)
        self.fc2 = nn.Linear(120, num_outputs)

    def forward(self, x):
        x = self.pool(F.relu(self.conv1(x)))
        x = self.pool(F.relu(self.conv2(x)))
        x = self.pool(F.relu(self.conv3(x)))
        x = self.pool(F.relu(self.conv4(x)))
        x = torch.flatten(x, 1)
        x = F.relu(self.fc1(x))
        x = self.fc2(x)
        return x


class Net_4conv_MultiHead(nn.Module): #Final CNN for Multi Head (12 classes for hours, 60 classes for minutes)
    def __init__(self):
        super().__init__()
        #Same layers for both heads
        self.conv1 = nn.Conv2d(1, 6, 3, padding=1)
        self.pool = nn.MaxPool2d(2, 2)
        self.conv2 = nn.Conv2d(6, 16, 3, padding=1)
        self.conv3 = nn.Conv2d(16, 32, 3, padding=1)
        self.conv4 = nn.Conv2d(32, 64, 3, padding=1)
        self.fc1 = nn.Linear(64 * 9 * 9, 120)
        #Two separate outputs
        self.hour_head = nn.Linear(120, 12) #head 1: hour
        self.minute_head = nn.Linear(120, 60) #head 2: minute

    def forward(self, x):
        x = self.pool(F.relu(self.conv1(x)))
        x = self.pool(F.relu(self.conv2(x)))
        x = self.pool(F.relu(self.conv3(x)))
        x = self.pool(F.relu(self.conv4(x)))
        x = torch.flatten(x, 1)
        x = F.relu(self.fc1(x))
        #two separate outputs
        return self.hour_head(x), self.minute_head(x)

