#Train the model
def train_regression(model, train_dataloader, optimizer, criterion, epochs):

    """Train a regression model for a given number of epochs."""

    for epoch in range(epochs):
        model.train()
        running_loss = 0.0

        for inputs, hours, minutes in train_dataloader:

            #To use external GPU
            inputs = inputs.to(device)
            hours = hours.to(device)
            minutes = minutes.to(device)

            #the time as a number of hours (e.g., 03:30 --> 3.5) (we compute it here!)
            target = (hours + minutes / 60.0).float()

            #zero the parameter gradients
            optimizer.zero_grad()

            #forward + backward + optimize
            outputs = model(inputs).squeeze(1) #predictions (one number per image)
            loss = criterion(outputs, target) #regression loss
            loss.backward() #compute gradients
            optimizer.step() #optimize weights

            #compute running loss
            running_loss += loss.item()

        print(
            f"Epoch {epoch + 1}/{epochs}: "
            f"- Loss = {running_loss/len(train_dataloader):.4f}"
        )

#Validate / test the model
def evaluate_regression(model, dataloader):

    """Evaluate a regression model using the average circular time error."""

    model.eval()
    total_error = 0
    total = 0

    with torch.no_grad():
        for inputs, hours, minutes in dataloader:
            #To use external GPU
            inputs = inputs.to(device)
            hours = hours.to(device)
            minutes = minutes.to(device)
            true_minutes = (hours * 60 + minutes).float()

            #Get predictions (in hours, e.g. 3.5)
            outputs = model(inputs).squeeze(1)
            predicted_hours = torch.remainder(outputs, 12.0) #restrict prediction in 12 hours range

            #Calculate absolute difference and the circular difference (in minutes!!)
            predicted_minutes = predicted_hours * 60.0 #We re-convert them in minutes to make it comparable with the other models
            difference = torch.abs(predicted_minutes - true_minutes)
            circular_difference = torch.minimum(difference, 720 - difference)

            #Compute the errors
            total_error += circular_difference.sum().item()
            total += minutes.size(0)

    common_sense_error = total_error / total
    return common_sense_error


