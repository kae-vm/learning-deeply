#Train the model

def train_model(model, train_dataloader, optimizer, criterion, epochs): #NEW: no more bin_size

    """Train a model for a given number of epochs."""

    for epoch in range(epochs):

        model.train()
        running_loss = 0.0

        for inputs, hours in train_dataloader:

            #data agumentation
            #inputs = train_transform(inputs)

            #To use external GPU
            inputs = inputs.to(device)
            hours = hours.to(device)

            #zero the parameter gradients
            optimizer.zero_grad()

            #forward + backward + optimize
            outputs = model(inputs).squeeze(1) #NEW: these are the new predictions
            loss = criterion(outputs, hours) #NEW: regression loss
            loss.backward() #compute gradients
            optimizer.step() #optimize weights

            #compute running loss
            running_loss += loss.item()
        print(
            f"Epoch {epoch + 1}/{epochs}: "
            f"- Loss = {running_loss/len(train_dataloader):.4f}"
        )

#Validate the model

def evaluate_model(model, dataloader): #NEW: no more bin_size

    """Evaluate a model using the average circular time error."""

    model.eval()

    total_error = 0
    total = 0

    with torch.no_grad():
        for inputs, hours in dataloader:

            #To use external GPU
            inputs = inputs.to(device)
            hours = hours.to(device)

            #Get predictions (in total number of minutes)
            outputs = model(inputs).squeeze(1) #NEW: predictions (in hours, 3.5!!!)
            predicted_hours = torch.remainder(outputs, 12.0) #NEW: restrict prediction in 12 hours range

            #Calculate absolute difference and the circular difference (in minutes!!)
            predicted_minutes = predicted_hours * 60.0 #We re-convert them in minutes to make it comparable with the other models
            true_minutes = hours * 60.0 #It doesn't affect the learning process
            difference = torch.abs(predicted_minutes - true_minutes)
            circular_difference = torch.minimum(difference, 720 - difference)

            #Compute the errors
            total_error += circular_difference.sum().item()
            total += hours.size(0)

    common_sense_error = total_error / total

    return common_sense_error

