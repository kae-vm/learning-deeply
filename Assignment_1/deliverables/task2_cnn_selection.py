#One function to be able to run the different experiments by changing one setting at a time
def run_experiment(NetClass, seed, init_fn=None, bin_size=30, epochs=20, lr=0.001, batch_size=64):

    #New seed for each experiment
    reset_seed(seed)

    #The training loader is built here, so that we can change the batch size
    train_loader = DataLoader(train_data, batch_size=batch_size, shuffle=True, generator=generator)

    num_classes = 720 // bin_size
    model = NetClass(num_classes).to(device)

    #Initialization weights
    if init_fn is not None:
        model.apply(init_fn)

    #Loss function
    criterion = nn.CrossEntropyLoss()

    #Optimizer
    optimizer = optim.Adam(model.parameters(), lr=lr)

    #Train the model
    train_model(model, train_loader, optimizer, criterion, epochs, bin_size)

    #Validate the model
    return evaluate_model(model, valid_dataloader, bin_size)

