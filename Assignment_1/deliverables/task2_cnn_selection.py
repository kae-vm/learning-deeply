#We use Net_4conv, default weights, lr = 0.001, 30-minute bins, 1 seed
#Here we use more epochs because we want to see where we can stop

def train_validate_curves(NetClass, seed, bin_size=30, epochs=50, lr=0.001):
    reset_seed(seed)
    num_classes = 720 // bin_size
    model = NetClass(num_classes).to(device)
    criterion = nn.CrossEntropyLoss()
    optimizer = optim.Adam(model.parameters(), lr=lr)

    train_losses, valid_losses, valid_errors = [], [], []
    for epoch in range(epochs):
        #training
        model.train()
        running_loss = 0.0
        for inputs, minutes in train_dataloader:
            inputs, minutes = inputs.to(device), minutes.to(device)
            labels_class = (minutes // bin_size).long()
            optimizer.zero_grad()
            loss = criterion(model(inputs), labels_class)
            loss.backward()
            optimizer.step()
            running_loss += loss.item()
        train_losses.append(running_loss / len(train_dataloader))

        #validation loss (no learning here)
        model.eval()
        running_loss = 0.0
        with torch.no_grad():
            for inputs, minutes in valid_dataloader:
                inputs, minutes = inputs.to(device), minutes.to(device)
                labels_class = (minutes // bin_size).long()
                running_loss += criterion(model(inputs), labels_class).item()
        valid_losses.append(running_loss / len(valid_dataloader))

        #validation common-sense error (the metric we really care about)
        valid_errors.append(evaluate_model(model, valid_dataloader, bin_size))

        print(f"Epoch {epoch + 1}/{epochs}: train loss = {train_losses[-1]:.4f}, "
              f"valid loss = {valid_losses[-1]:.4f}, valid error = {valid_errors[-1]:.2f} min")

    return model, train_losses, valid_losses, valid_errors


